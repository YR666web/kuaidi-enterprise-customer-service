OUT = "栈语项目_AI应用开发实习全流程面试题库与参考回答.docx"
NAVY = "17365D"
BLUE = "2F5597"
BORDER = "D9D9D9"


def keep_with_next(p):
    pPr = p._p.get_or_add_pPr()
    pPr.append(OxmlElement("w:keepNext"))


def set_repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trPr.append(el)


def set_cell(cell, fill=None):
    tcPr = cell._tc.get_or_add_tcPr()
    if fill:
        shd = OxmlElement("w:shd")
        shd.set(qn("w:fill"), fill)
        tcPr.append(shd)
    borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), BORDER)
        borders.append(e)
    tcPr.append(borders)
    margins = OxmlElement("w:tcMar")
    for edge, value in (("top", 90), ("start", 120), ("bottom", 90), ("end", 120)):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:w"), str(value))
        e.set(qn("w:type"), "dxa")
        margins.append(e)
    tcPr.append(margins)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def table(doc, headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    set_repeat_header(t.rows[0])
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        set_cell(c, NAVY)
        c.width = Cm(widths[i])
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        r.bold = True
        r.font.color.rgb = RGBColor(255, 255, 255)
        r.font.size = Pt(9)
    for ridx, row in enumerate(rows):
        cells = t.add_row().cells
        for i, value in enumerate(row):
            c = cells[i]
            set_cell(c, "F7F9FC" if ridx % 2 else None)
            c.width = Cm(widths[i])
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.add_run(str(value))
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(2)
        p.add_run(item)


def qa(doc, idx, question, answer, follow=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after = Pt(2)
    keep_with_next(p)
    r = p.add_run(f"{idx}. {question}")
    r.bold = True
    r.font.color.rgb = RGBColor.from_string(BLUE)
    a = doc.add_paragraph()
    a.paragraph_format.left_indent = Cm(0.45)
    a.paragraph_format.space_after = Pt(3)
    lead = a.add_run("参考回答：")
    lead.bold = True
    a.add_run(answer)
    if follow:
        f = doc.add_paragraph()
        f.paragraph_format.left_indent = Cm(0.45)
        f.paragraph_format.space_after = Pt(5)
        lead = f.add_run("可能追问：")
        lead.bold = True
        lead.italic = True
        rr = f.add_run(follow)
        rr.italic = True
        rr.font.color.rgb = RGBColor(80, 80, 80)


